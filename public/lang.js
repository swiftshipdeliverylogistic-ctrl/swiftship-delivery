window.translations = translations;

function t(key, variables) {
  variables = variables || {};
  const lang = localStorage.getItem("swiftship_lang") || DEFAULT_LANGUAGE;
  let text = (translations[lang] && translations[lang][key])
          || (translations[DEFAULT_LANGUAGE] && translations[DEFAULT_LANGUAGE][key])
          || null;
  if (!text) {
    const fallback = key.split(".").pop();
    return fallback.replace(/([A-Z])/g, " $1").replace(/^./, function(c){ return c.toUpperCase(); });
  }
  return String(text).replace(/\{(\w+)\}/g, function(_, name) {
    return variables[name] !== undefined ? variables[name] : "{" + name + "}";
  });
}

function applyLanguage(lang) {
  if (!translations[lang]) lang = DEFAULT_LANGUAGE;
  const dict = translations[lang];

  document.querySelectorAll("[data-i18n]").forEach(function(el) {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
    else if (translations.en[key]) el.textContent = translations.en[key];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(function(el) {
    const key = el.getAttribute("data-i18n-ph");
    if (dict[key]) el.placeholder = dict[key];
    else if (translations.en[key]) el.placeholder = translations.en[key];
  });
  document.querySelectorAll("[data-i18n-title]").forEach(function(el) {
    const key = el.getAttribute("data-i18n-title");
    if (dict[key]) el.title = dict[key];
    else if (translations.en[key]) el.title = translations.en[key];
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach(function(el) {
    const key = el.getAttribute("data-i18n-aria-label");
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
    else if (translations.en[key]) el.setAttribute("aria-label", translations.en[key]);
  });

  document.documentElement.lang = lang;
  document.documentElement.dir = languageDirection[lang] || "ltr";
  localStorage.setItem("swiftship_lang", lang);
  const sel = document.getElementById("lang-switch");
  if (sel) sel.value = lang;

  window.dispatchEvent(new CustomEvent("swiftship:languageChanged", { detail: { language: lang } }));
}

(function() {
  const saved = localStorage.getItem("swiftship_lang");
  let lang = saved;
  if (!lang) {
    const browser = (navigator.language || "en").slice(0, 2).toLowerCase();
    lang = translations[browser] ? browser : DEFAULT_LANGUAGE;
  }
  document.addEventListener("DOMContentLoaded", function() { applyLanguage(lang); });
})();

